      const rows = brands
        .filter((b) => b.category === c.name)
        .map((b) => {
          const colors = b.colors.length ? `<sub>${b.colors.join(' ')}</sub>` : '';
          return `| [${esc(b.name)}](design-md/${b.host}/)<br><sub>${b.host}</sub> | ${themeLabel(b)} | ${fontList(b)} | ${colors} | [DESIGN.md](design-md/${b.host}/DESIGN.md), [style guide](${pageUrl(b)}) |`;
        });
      return `### ${esc(c.name)}

${c.count} ${c.count === 1 ? 'brand' : 'brands'}.

| Brand | Theme | Fonts | Colors | Links |
| --- | --- | --- | --- | --- |
${rows.join('\n')}`;
