function indexJson(brands, categories) {
  return {
    name: 'Sitepeel DESIGN.md library',
    source: LIBRARY_URL,
    license: 'CC-BY-4.0',
    credit: 'Sitepeel (sitepeel.dev)',
    count: brands.length,
    categories,
    brands: brands.map((b) => ({
      name: b.name,
      host: b.host,
      category: b.category,
      theme: b.theme,
      fonts: b.fonts,
      colors: b.colors,
      accent: b.accent,
      file: `design-md/${b.host}/DESIGN.md`,
      raw: rawUrl(b),
      sitepeel: pageUrl(b),
      screenshot: `${pageUrl(b)}screenshot.jpg`,
    })),
  };
}

async function main() {
  const index = await get(INDEX_URL);
  if (/html/i.test(index.type)) throw new Error(`The index came back as ${index.type}, not markdown.`);
  const { brands, categories } = parseIndex(index.body.toString('utf8'));

  const before = await brandFolders();
  const previous = await previousCount(before);
  if (brands.length < previous * MIN_KEEP) {
    throw new Error(`The index lists ${brands.length} brands but the repo has ${previous}. That is below ${MIN_KEEP * 100}%, so nothing was changed.`);
  }

  const files = await mapPool(brands, CONCURRENCY, async (b) => {
    try {
      const res = await get(b.fileUrl);
      const problem = designMdProblem(res);
      return problem ? { error: `${b.fileUrl}: ${problem}` } : { body: res.body };
    } catch (err) {
      return { error: err.message };
    }
  });
  const errors = files.filter((f) => f.error).map((f) => f.error);
  if (errors.length) throw new Error(`${errors.length} of ${brands.length} files failed, so nothing was changed:\n  ${errors.join('\n  ')}`);

  // Everything checked out. Only now touch the disk.
  const stats = { added: 0, updated: 0, removed: 0 };
  const keep = new Set(brands.map((b) => b.host));
  await mkdir(LIBRARY_DIR, { recursive: true });
  for (const [i, b] of brands.entries()) {
    const dir = path.join(LIBRARY_DIR, b.host);
    const isNew = !before.includes(b.host);
    await mkdir(dir, { recursive: true });
    const changed = await writeIfChanged(path.join(dir, 'DESIGN.md'), files[i].body);
    await writeIfChanged(path.join(dir, 'README.md'), brandReadme(b));
    if (isNew) stats.added++;
    else if (changed) stats.updated++;
  }
  for (const name of before) {
    if (keep.has(name)) continue;
    await rm(path.join(LIBRARY_DIR, name), { recursive: true, force: true });
    stats.removed++;
  }
  await writeIfChanged(path.join(ROOT, 'index.json'), `${JSON.stringify(indexJson(brands, categories), null, 2)}\n`);
  await writeIfChanged(path.join(ROOT, 'README.md'), rootReadme(brands, categories));

  const summary = `Synced ${brands.length} brands: ${stats.added} added, ${stats.updated} updated, ${stats.removed} removed.`;
  console.log(summary);
  if (process.env.GITHUB_STEP_SUMMARY) await appendFile(process.env.GITHUB_STEP_SUMMARY, `${summary}\n`);
}

main().catch((err) => {
  console.error(`Sync stopped: ${err.message}`);
  process.exitCode = 1;
});
