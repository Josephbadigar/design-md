#!/usr/bin/env node
// Syncs this repo with the Sitepeel DESIGN.md library: https://sitepeel.dev/design-md/examples/
// Node 20 or newer, no dependencies. Usage: node scripts/sync.mjs
//
// Nothing on disk changes unless the index parses, still lists at least 90% of the
// brands already in the repo, and every file downloads and looks like a DESIGN.md.
// A challenge page or an outage makes the script exit non-zero and leaves the repo as it is.

import { existsSync } from 'node:fs';
import { appendFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIBRARY_DIR = path.join(ROOT, 'design-md');
const SITE = 'https://sitepeel.dev';
const LIBRARY_URL = `${SITE}/design-md/examples/`;
const INDEX_URL = `${LIBRARY_URL}index.md`;
const REPO = 'Josephbadigar/design-md';
// Shown with screenshots at the top of the README, in this order (missing ones are skipped).
const FEATURED = ['stripe.com', 'linear.app', 'vercel.com', 'notion.com', 'figma.com', 'apple.com', 'anthropic.com', 'cursor.com', 'supabase.com'];
const RAW_BASE = `https://raw.githubusercontent.com/${REPO}/main`;
const USER_AGENT = `sitepeel-design-md-sync (+https://github.com/${REPO})`;
const CONCURRENCY = 6;
const MIN_KEEP = 0.9;
const HOST_RE = /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$/i;
const ENTRY_RE = new RegExp(`^- \\[(.+?)\\]\\(${SITE.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}\\/design-md\\/([^/)]+)\\/\\) \\(([^)]+)\\): (.*)$`);
const GENERATED ='<!-- Generated by scripts/sync.mjs from the Sitepeel library. Edit the script, not this file. -->';

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function get(url, attempts = 4) {
  let last;
  for (let i = 1; i <= attempts; i++) {
    try {
      const res = await fetch(url, {
        headers: { 'user-agent': USER_AGENT, accept: 'text/markdown, text/plain;q=0.9, */*;q=0.1' },
        signal: AbortSignal.timeout(30_000),
      });
      if (res.ok) return { type: res.headers.get('content-type') || '', body: Buffer.from(await res.arrayBuffer()) };
      const challenge = res.headers.get('cf-mitigated') === 'challenge' ? ' (Cloudflare challenge)' : '';
      last = new Error(`HTTP ${res.status}${challenge}`);
      // A block or a missing file won't fix itself in a few seconds.
      if (res.status < 500 && res.status !== 429) break;
    } catch (err) {
      last = err;
    }
    if (i < attempts) await sleep(1000 * 2 ** i);
  }
  throw new Error(`${url}: ${last.message}`);
}

async function mapPool(items, limit, fn) {
  const out = new Array(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i]);
    }
  };
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return out;
}

// index.md has "## Category (N)" headings, each followed by lines like:
// - [Linear](https://sitepeel.dev/design-md/linear.app/) (linear.app): dark theme; type Inter Variable;
//   colors #08090A, #0F1011; accent #E5E5E6. File: https://sitepeel.dev/design-md/linear.app/DESIGN.md
function parseIndex(text) {
  const brands = [];
  const categories = [];
  const seen = new Set();
  let category = null;

  for (const line of text.split(/\r?\n/)) {
    const heading = line.match(/^## (.+?) \((\d+)\)\s*$/);
    if (heading) {
      category = { name: heading[1], declared: Number(heading[2]), listed: 0, count: 0 };
      categories.push(category);
      continue;
    }
    if (line.startsWith('## ')) {
      category = null;
      continue;
    }
    if (!category || !line.startsWith('- [')) continue;

    const m = line.match(ENTRY_RE);
    if (!m) throw new Error(`Unreadable index line: ${line}`);
    const [, name, host, shownHost, rest] = m;
    category.listed++;

    if (!HOST_RE.test(host) || host !== shownHost) throw new Error(`Unexpected host in index line: ${line}`);
    const file = rest.match(/^(.*?)\.?\s*File: (\S+)\s*$/);
    if (!file || file[2] !== `${SITE}/design-md/${host}/DESIGN.md`) throw new Error(`Unexpected file link in index line: ${line}`);
    if (seen.has(host)) {
      console.warn(`Skipping duplicate ${host} in ${category.name}`);
      continue;
    }
    seen.add(host);

    const brand = { name, host, category: category.name, theme: '', fonts: [], colors: [], accent: '', fileUrl: file[2] };
    for (const part of file[1].split(';').map((s) => s.trim())) {
      let f;
      if ((f = part.match(/^(\w+) theme$/))) brand.theme = f[1].toLowerCase();
      else if ((f = part.match(/^type (.+)$/))) brand.fonts = f[1].split(',').map((s) => s.trim()).filter(Boolean);
      else if ((f = part.match(/^colors (.+)$/))) brand.colors = (f[1].match(/#[0-9a-f]{3,8}\b/gi) || []).map((c) => c.toUpperCase());
      else if ((f = part.match(/^accent (#[0-9a-f]{3,8})$/i))) brand.accent = f[1].toUpperCase();
    }
    category.count++;
    brands.push(brand);
  }

  if (!brands.length) throw new Error('The index lists no brands.');
  for (const c of categories) {
    if (c.listed !== c.declared) throw new Error(`"${c.name}" says ${c.declared} brands but lists ${c.listed}. The index may be cut off.`);
  }
  const complete = brands.filter((b) => b.theme && b.colors.length).length;
  if (complete < brands.length * MIN_KEEP) throw new Error(`Only ${complete} of ${brands.length} index lines have a theme and colors. The format may have changed.`);

  return { brands, categories: categories.filter((c) => c.count).map(({ name, count }) => ({ name, count })) };
}

function designMdProblem({ type, body }) {
  if (/html/i.test(type)) return `came back as ${type}`;
  const text = body.toString('utf8');
  const front = text.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
  if (!front) return 'no front matter at the top';
  if (!/^colors:/m.test(front[1])) return 'no colors: in the front matter';
  return null;
}

async function brandFolders() {
  if (!existsSync(LIBRARY_DIR)) return [];
  const entries = await readdir(LIBRARY_DIR, { withFileTypes: true });
  return entries.filter((e) => e.isDirectory()).map((e) => e.name);
}

async function previousCount(folders) {
  let listed = 0;
  try {
    listed = JSON.parse(await readFile(path.join(ROOT, 'index.json'), 'utf8')).count || 0;
  } catch {}
  return Math.max(folders.length, listed);
}

async function writeIfChanged(file, content) {
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  try {
    if ((await readFile(file)).equals(next)) return false;
  } catch {}
  await writeFile(file, next);
  return true;
}

const esc = (s) => String(s).replace(/[\\`*_[\]<>|]/g, '\\$&');
const slug = (s) => s.toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-');
const pageUrl = (b) => `${SITE}/design-md/${b.host}/`;
const rawUrl = (b) => `${RAW_BASE}/design-md/${b.host}/DESIGN.md`;
const fontList = (b) => (b.fonts.length ? b.fonts.map(esc).join(', ') : 'Not listed');
const themeLabel = (b) => (b.theme ? b.theme[0].toUpperCase() + b.theme.slice(1) : 'Not listed');

function brandReadme(b) {
  const colors = b.colors.length ? b.colors.map((c) => `\`${c}\``).join(' ') : 'Not listed';
  return `${GENERATED}

# ${esc(b.name)} DESIGN.md

The DESIGN.md file for ${b.host}, in the ${esc(b.category)} category. [Sitepeel](${pageUrl(b)}) measured it from the live site.

- Theme: ${b.theme || 'not listed'}
- Fonts: ${fontList(b)}
- Colors: ${colors}
- Accent: ${b.accent ? `\`${b.accent}\`` : 'not listed'}

[![${esc(b.name)} home page](${pageUrl(b)}screenshot.jpg)](${pageUrl(b)})

See every color, font and component on the [${esc(b.name)} style guide](${pageUrl(b)}) on sitepeel.dev.

How to use: save [DESIGN.md](DESIGN.md) in your project's root folder and tell your agent to follow it.

\`\`\`sh
curl -o DESIGN.md ${rawUrl(b)}
\`\`\`

Need another site? The free [DESIGN.md generator](${SITE}/design-md/) makes one from any link, and the [Sitepeel MCP server](${SITE}/mcp/) lets your agent fetch it on its own.

[Back to all brands](../../README.md)
`;
}

